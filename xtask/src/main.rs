//! Generate `crates/igs-iso9506-mms-codec/src/generated/` from the licensed data files of
//! IMPLEMENTATION.md section 3. `cargo xtask codegen` writes them; `cargo xtask codegen --check`
//! fails when the committed files are stale. No comment of a module is copied. `docs/spec/` is
//! absent in CI, so codegen runs only on a dev machine.

use std::fs;
use std::io::ErrorKind;
use std::path::{Path, PathBuf};
use std::process::Command;

mod asn;
mod data;
mod emit;
mod profile81;

use asn::{Fail, Module};
use data::{validate, Conformance, Profile};
use emit::{tables_txt, Generator};

const MODULES: [&str; 5] = [
    "docs/spec/9506-2/data/asn1/variante_61850/ISO-9506-MMS-1.asn",
    "docs/spec/9506-2/data/asn1/variante_61850/ISO-9506-MMS-1A.asn",
    "docs/spec/9506-2/data/asn1/variante_61850/MMS-Environment-1.asn",
    "docs/spec/9506-1/data/asn1/variante_61850/MMS-Object-Module-1.asn",
    "docs/spec/X.227/data/asn1/variante_if/ACSE-1.asn",
];

const HEADER: &str = "// SPDX-FileCopyrightText: 2026 The igs-iso9506-mms contributors
//
// SPDX-License-Identifier: Apache-2.0
";

const BANNER_TYPES: &str = "
//! ASN.1 types of the MMS and ACSE PDUs, with their tags.
//!
//! Generated by `cargo xtask codegen`, do not edit.
//! Sources: ISO 9506-2 §7, §8, §10, §14, annex E, ISO 9506-1 §10, §14, ITU-T X.227 Amd.1 §9.1;
//! tags of the directory names: ITU-T X.501 §9.2, §9.3. The codec of each type uses the runtime
//! of `crate::asn`.
";

const BANNER_TABLES: &str = "
//! Service, CBB and error tables of MMS, and what the profile requires.
//!
//! Generated by `cargo xtask codegen`, do not edit.
//! Sources: ISO 9506-2 §7, §8.2, §25, ISO 9506-1 §10, IEC 60870-6-702 annex A.
";

const MOD_TEXT: &str = "
//! Generated code; see the banner of each file.
//!
//! Generated by `cargo xtask codegen`, do not edit.

pub mod profile_81;
pub mod tables;
pub mod types;
";

fn main() {
    let mut args = std::env::args().skip(1);
    let command = args.next();
    let check = args.any(|a| a == "--check");
    let result = match command.as_deref() {
        Some("codegen") => run(check),
        _ => {
            println!("usage: cargo xtask codegen [--check]");
            Ok(())
        }
    };
    if let Err(e) = result {
        eprintln!("xtask: {e}");
        std::process::exit(1);
    }
}

fn workspace_root() -> Result<PathBuf, Fail> {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .map(Path::to_path_buf)
        .ok_or_else(|| "xtask must live inside the workspace".into())
}

fn read(path: &Path) -> Result<String, Fail> {
    fs::read_to_string(path).map_err(|e| {
        if e.kind() == ErrorKind::NotFound {
            format!(
                "input {} missing: the data files of IMPLEMENTATION.md section 3 \
                 (docs/spec symlink) must be present to run codegen",
                path.display()
            )
            .into()
        } else {
            e.into()
        }
    })
}

fn run(check: bool) -> Result<(), Fail> {
    let root = workspace_root()?;
    let profile: Profile =
        serde_saphyr::from_str(&read(&root.join("docs/spec/9506-2/data/profile_mms.yaml"))?)?;
    let mut conformance: Conformance = serde_saphyr::from_str(&read(
        &root.join("docs/spec/6-702/data/conformance_702.yaml"),
    )?)?;
    validate(&profile, &conformance)?;
    // ReadJournal is required by the IEC 61850 profile once the log services are declared (8-1 table 128, condition c13 of
    // readJournal: "Shall be 'm' if support for the ACSI QueryLogByTime or QueryLogAfter is declared"). TASE.2 does not require it, so
    // it is added with its own scope: its types are generated, and the TASE.2 tables are unchanged.
    // The file services of GetFile (open, read, close), DeleteFile (delete) and GetFileAttributeValues (directory) (8-1 clause 23;
    // N8). SetFile needs ObtainFile, which is not served; its tag is not in the scope.
    for (name, tag) in [
        ("ReadJournal", 65),
        ("fileOpen", 72),
        ("fileRead", 73),
        ("fileClose", 74),
        ("fileDelete", 76),
        ("fileDirectory", 77),
    ] {
        conformance.mms_services.push(data::ProfileService {
            name: name.to_string(),
            scope: "iec61850".to_string(),
            tag: Some(tag),
            family: Some("confirmed".to_string()),
            client: data::Status::default(),
            server: data::Status::default(),
        });
    }
    let profile81: profile81::Conformance81 =
        serde_saphyr::from_str(&read(&root.join("docs/spec/8-1/data/conformance_81.yaml"))?)?;

    let mut modules = Vec::new();
    for path in MODULES {
        modules.push(Module::parse(&read(&root.join(path))?)?);
    }
    for module in &modules {
        for name in module.assignments.keys() {
            module.type_of(name)?;
        }
    }
    let mut generator = Generator::new(&modules, &conformance);
    generator.run()?;

    let out = root.join("crates/igs-iso9506-mms-codec/src/generated");
    let texts = [
        ("mod.rs", fmt(&format!("{HEADER}{MOD_TEXT}"))),
        (
            "tables.rs",
            fmt(&tables_txt(
                &format!("{HEADER}{BANNER_TABLES}"),
                &profile,
                &conformance,
            )?),
        ),
        (
            "types.rs",
            fmt(&generator.types_txt(&format!("{HEADER}{BANNER_TYPES}"))?),
        ),
        (
            "profile_81.rs",
            fmt(&format!(
                "{HEADER}//! The IEC 61850 profile rules, from IEC 61850-8-1 clause 24 (PICS); D-033.\n\n{}",
                profile81::rules_txt(&profile81)?
            )),
        ),
    ];

    if check {
        for (name, expect) in &texts {
            let path = out.join(name);
            let have = fs::read_to_string(&path).map_err(|_| {
                format!(
                    "{} missing: run `cargo xtask codegen` and commit",
                    path.display()
                )
            })?;
            if &have != expect {
                return Err(format!(
                    "{} is stale: run `cargo xtask codegen` and commit",
                    path.display()
                )
                .into());
            }
        }
        println!("codegen: committed files are up to date");
        return Ok(());
    }

    fs::create_dir_all(&out)?;
    for (name, text) in &texts {
        fs::write(out.join(name), text)?;
        println!("wrote {}", out.join(name).display());
    }
    Ok(())
}

fn fmt(text: &str) -> String {
    let dir = std::env::temp_dir().join("igs-iso9506-mms-codegen");
    let _ = fs::create_dir_all(&dir);
    let path = dir.join("g.rs");
    let ok = fs::write(&path, text).is_ok()
        && Command::new("rustfmt")
            .arg("--edition=2021")
            .arg(&path)
            .output()
            .is_ok_and(|o| o.status.success());
    let out = if ok {
        fs::read_to_string(&path).unwrap_or_else(|_| text.to_owned())
    } else {
        text.to_owned()
    };
    let _ = fs::remove_dir_all(&dir);
    out
}
